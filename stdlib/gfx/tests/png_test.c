static bool inflates(const uint8_t *const z, const uint32_t n, const uint32_t want)
{
    uint8_t got[100], expect[100];
    uint32_t made = 0;
    text(expect, want);
    return inflate_zlib(z, n, got, sizeof got, &made) && made == want && !memcmp(got, expect, want);
}

TEST(gfx_inflate_each_block_type)
{
    CHECK(inflates(stored, sizeof stored, 20));
    CHECK(inflates(fixed, sizeof fixed, 100));
    CHECK(inflates(dynamic, sizeof dynamic, 100));
}

/* A byte changed fails the Adler-32; room for less than it makes fails. */
TEST(gfx_inflate_refuses_bad_streams)
{
    uint8_t bad[sizeof fixed], out[100];
    uint32_t made;
    memcpy(bad, fixed, sizeof bad);
    bad[sizeof bad - 1] ^= 1;
    CHECK(!inflate_zlib(bad, sizeof bad, out, sizeof out, &made));
    CHECK(!inflate_zlib(fixed, sizeof fixed, out, 99, &made));
    CHECK(!inflate_zlib(fixed, 10, out, sizeof out, &made));
}

static uint32_t pixel(const Image *const img, const int32_t x, const int32_t y)
{
    const uint32_t i = (uint32_t)(y * img->w + x);
    uint32_t c = 0;

    if (img->format == PX_8)
        return img->pixels[i];

    memcpy(&c, img->pixels + 4 * i, 4);
    return c;
}

/* img's pixels, row by row, are want's. */
static bool pixels(const Image *const img, const uint32_t *const want)
{
    for (int32_t y = 0; y < img->h; y++)
        for (int32_t x = 0; x < img->w; x++)
            if (pixel(img, x, y) != want[y * img->w + x])
                return false;

    return true;
}

static Image read(const uint8_t *const data, const uint32_t n, const int32_t w, const int32_t h)
{
    Image img = {};

    CHECK(img_load(data, n, &img) == IMG_OK && img.w == w && img.h == h);
    return img;
}

static void done(Image img)
{
    mem_free(img.pixels);
    mem_free(img.palette);
}

/* 2 bits, rows 0 1 2 and 3 2 1; black, red, green, blue; green transparent. It swaps with 0. */
TEST(gfx_png_indexed_keeps_8_bits)
{
    gfx_fresh(S);
    const Image img = read(one_keyed, sizeof one_keyed, 3, 2);
    static const uint32_t want[] = {2, 1, 0, 3, 0, 1};

    CHECK(img.format == PX_8 && pixels(&img, want));
    CHECK(
        img.palette[0] == 0x00FF00 && img.palette[1] == 0xFF0000 && img.palette[2] == 0 &&
        img.palette[3] == 0x0000FF
    );
    done(img);
}

/* The same with black and green transparent: two keys, so 32 bits, alpha tRNS's. */
TEST(gfx_png_indexed_with_two_keys_is_32_bits)
{
    gfx_fresh(S);
    const Image img = read(two_keyed, sizeof two_keyed, 3, 2);
    static const uint32_t want[] = {0, 0xFFFF0000, 0x0000FF00, 0xFF0000FF, 0x0000FF00, 0xFFFF0000};

    CHECK(img.format == PX_32 && !img.palette && pixels(&img, want));
    done(img);
}

/* RGBA's rows filtered sub, up, average and Paeth. */
TEST(gfx_png_rgba_undoes_each_filter)
{
    gfx_fresh(S);
    const Image img = read(rgba, sizeof rgba, 2, 4);
    static const uint32_t want[] = {
        0xFFC80A1E,
        0x805AFA07,
        0xFFC90C21,
        0x001103FA,
        0x4005B463,
        0xFFFAF0E6,
        0x04010203,
        0x83808182
    };

    CHECK(img.format == PX_32 && pixels(&img, want));
    done(img);
}

/* 16-bit grey &H1234 and &HABCD, tRNS &H1234; 1-bit grey 101100111 across two bytes. */
TEST(gfx_png_grey_of_16_and_1_bits)
{
    gfx_fresh(S);
    const Image deep = read(grey16, sizeof grey16, 2, 1);
    static const uint32_t want16[] = {0x00121212, 0xFFABABAB};

    CHECK(pixels(&deep, want16));
    done(deep);

    const Image bits = read(grey1, sizeof grey1, 9, 1);
    const uint32_t k = 0xFF000000, w = 0xFFFFFFFF;
    const uint32_t want1[] = {w, k, w, w, k, k, w, w, w};

    CHECK(pixels(&bits, want1));
    done(bits);
}

TEST(gfx_png_refuses_interlaced_and_cut_short)
{
    gfx_fresh(S);
    Image img;
    CHECK(img_load(interlaced, sizeof interlaced, &img) == IMG_NOT_ONE);
    CHECK(img_load(rgba, sizeof rgba - 20, &img) == IMG_NOT_ONE);
    CHECK(img_load(rgba, 7, &img) == IMG_NOT_ONE);
}

static int32_t load(Session *const S, const uint8_t *const data, const uint32_t n)
{
    FILE *const f = fopen("build/host/gfx/test.png", "wb");
    CHECK(f && fwrite(data, n, 1, f) == 1);
    fclose(f);
    const int32_t s = CALL("surface.load", STR("build/host/gfx/test.png")).result.i;
    remove("build/host/gfx/test.png");
    return s;
}

TEST(gfx_load_a_png)
{
    gfx_fresh(S);
    const int32_t indexed = load(S, one_keyed, sizeof one_keyed);
    CHECK(indexed && CALL("surface.bits", I(indexed)).result.i == 8);
    CHECK(CALL("surface.point", I(indexed), I(0), I(0)).result.i == 2);

    const int32_t argb = load(S, rgba, sizeof rgba);
    CHECK(argb && CALL("surface.bits", I(argb)).result.i == 32);
    CHECK(CALL("surface.point", I(argb), I(0), I(0)).result.i == 0xC80A1E);
}
