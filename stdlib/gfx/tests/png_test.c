/* 100 bytes of a, b, c and d, skewed so zlib picks a dynamic code: by an LCG. */
static void text(uint8_t *const out, const uint32_t n)
{
    uint32_t x = 1;

    for (uint32_t i = 0; i < n; i++) {
        x = x * 1103515245u + 12345u;
        out[i] = (uint8_t)"aaaaaaabbbcd"[(x >> 16) % 12];
    }
}

