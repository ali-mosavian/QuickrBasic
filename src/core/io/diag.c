/* A compile error in words, for the person who wrote the line.
 *
 * # How it works
 * An error is its E_* code, its DG_ code (io/msg.h; 0: found by BC's name and the text at the
 * error) and its column in the line's text. diag_at reads the place; diag_say prints what is
 * wrong, what to do, and the statement's form. The wording comes from llrm's front/explain.rs.
 *
 * diag_raise reports an error found off the code (the block pass), raised as if an ERR op at body
 * offset at of line (a program store offset) raised it, never trapped. other is its {other} text,
 * len bytes (31 at most kept). vm.opip is set to an ErrOp (vm/exec.h) of diag's own.
 *
 * # asm structure (retired/asm32/io/diag.asm, msg.inc)
 * | asm | here | |
 * |---|---|---|
 * | dx_at | diag_at | MIRROR; place error code, dg and state, returns the column the text is about |
 * | dx_raise | diag_raise | MIRROR |
 * | dx_say, dx_what | diag_say, diag_what | MIRROR |
 * | dx_todo, dx_shape | diag_todo, diag_shape | MIRROR; true when printed |
 * | dx_back, dx_stmt, dx_alpha, dx_upper, dx_name, dx_isw, dx_streq, dx_skip, dx_form, dx_find, dx_res, dx_syn, dx_sent, dx_fill, dx_p* | static | MIRROR |
 * | g_dx* data, g_dxr | static (g_dxr an ErrOp) | MIRROR |
 * | DG_* (msg.inc) | DG_* (io/msg.h) | D1 |
 * | g_dxmsg, g_dxfrm | diag_msgs, diag_forms | D1 |
 *
 * - D1. msg.h is generated by tools/x86msg.py; the tables are defined under DIAG_DATA.
 */
#define DIAG_DATA
#include "io/diag.h"
#include "comp/comp.h"
#include "comp/lexer.h"
#include "io/console.h"
#include "io/errmsg.h"

enum { STM_MAX = sizeof((Diag *)nullptr)->stm - 1 };

static const char *const leads[] = {
    "SUB",   "FUNCTION", "TYPE", "DECLARE", "CALL",  "STATIC", "SHARED", "DIM",  "REDIM", "COMMON",
    "CONST", "DEF",      "END",  "EXIT",    "ERASE", "SELECT", "CASE",   "GOTO", "GOSUB", "RETURN",
};

/* A name's or a number's byte: a letter, a digit or . _ $ % & ! # @. */
static bool is_word(const char c)
{
    if (is_digit((uint8_t)c) || is_letter((uint8_t)c))
        return true;

    return c && strchr("._$%&!#@", c);
}

/* The letters at s, at most max. */
static uint32_t letters(const char *const s, const uint32_t max)
{
    uint32_t n = 0;

    while (n < max && is_letter((uint8_t)s[n]))
        n++;

    return n;
}

/* n bytes of s to d in capitals, 0 after. */
static void upper(char *const d, const char *const s, const uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        d[i] = (char)upcase((uint8_t)s[i]);

    d[n] = 0;
}

/* The tables (diag.h) are runs of 0-ended strings: a form's entry two (word, form), a message's
   three (name, what, todo); an empty string ends a table. */
static const char *skip(const char *const s) { return s + strlen(s) + 1; }
static const char *next_form(const char *const e) { return skip(skip(e)); }
static const char *next_msg(const char *const e) { return skip(skip(skip(e))); }

/* The form of statement word w, nullptr none. */
static const char *form_of(const char *const w)
{
    for (const char *e = diag_forms; *e; e = next_form(e))
        if (!strcmp(e, w))
            return skip(e);

    return nullptr;
}

/* The entry named key, nullptr none. */
static const char *entry(const char *const key)
{
    for (const char *e = diag_msgs; *e; e = next_msg(e))
        if (!strcmp(e, key))
            return e;

    return nullptr;
}

/* The item before column col: col and len at it; none: len 0. */
static void diag_back(Diag *const d, const uint32_t col)
{
    const char *s = d->line;
    uint32_t b = col;

    while (b && s[b - 1] == ' ')
        b--;
    if (!b) {
        d->len = 0;
        return;
    }

    const uint32_t end = b--;

    if (s[b] == '"') {
        while (b && s[--b] != '"') {
        }
    } else if (is_word(s[b])) {
        while (b && is_word(s[b - 1]))
            b--;
    }

    d->col = b;
    d->len = end - b;
}

/* stm: the statement's first word, if a keyword; first when the error is at that word. */
static void diag_statement(Diag *const d)
{
    const char *const s = d->line;
    const uint32_t c = d->col;
    uint32_t start = 0;
    bool quoted = false;

    for (uint32_t i = 0; i < c; i++) { /* past the last ':' out of quotes */
        if (s[i] == '"')
            quoted = !quoted;
        if (s[i] == ':' && !quoted)
            start = i + 1;
    }

    while (start < c && (s[start] == ' ' || is_digit((uint8_t)s[start])))
        start++; /* past blanks and a line number */
    const char *w = s + start;
    uint32_t n = letters(w, c - start);
    d->first = !n;

    if (n < 2) {
        if (!d->first) { /* at the start: the word at the error */
            d->stm[0] = 0;
            return;
        }

        w = s + d->col;
        n = letters(w, 255);

        if (n < 2) {
            d->stm[0] = 0;
            return;
        }
    }

    upper(d->stm, w, n > STM_MAX ? STM_MAX : n);

    if (form_of(d->stm))
        return;

    const uint8_t *p = (const uint8_t *)d->stm; /* a keyword, if no form for it */
    if (!lexr_keyword(&p) || *p)
        d->stm[0] = 0;
}

/* name: the first word from the error on that is no leading keyword (p in SUB p (a%)). */
static void diag_name(Diag *const d)
{
    const char *b = d->line + d->col;
    d->namelen = 0;

    for (;;) {
        while (*b == ' ')
            b++;

        uint32_t n = 0;

        while (is_word(b[n]))
            n++;
        if (!n)
            return;

        upper(d->key, b, n < sizeof d->key ? n : sizeof d->key - 1);
        bool lead = false;

        for (size_t i = 0; i < countof(leads) && !lead; i++)
            lead = !strcmp(d->key, leads[i]);
        if (!lead) {
            d->name = b;
            d->namelen = n;
            return;
        }

        b += n;
    }
}

static const char *const s_syntax = "Syntax error";

/* A syntax error in words: what was found where, then the statement's form. */
static void diag_syntax(Diag *const d)
{
    d->bc = s_syntax;
    bool done = false;

    if (d->first && d->len) { /* at the statement's first word, a word: that one is it */
        const uint32_t n = letters(d->line + d->col, d->len);

        if (n == d->len && n <= STM_MAX) {
            upper(d->stm, d->line + d->col, n);
            d->what = "`{text}` cannot be used here: it does not start a valid statement at this "
                      "point";
            done = true;
        }
    }

    if (!done) {
        const char *names[256];

        if (d->state != DX_NOSTATE && comp_expnames(d->state, names)) {
            d->what = "expected {expected} in the {stm}, but found {found}";
        } else {
            d->what = d->len ? "`{text}` does not fit the {stm} here"
                             : "the {stm} is incomplete: the line ends where more is needed";
        }
    }

    d->todo = "check the statement against the manual; the mark shows where it stopped being "
              "understood";
    const char *const f = form_of(d->stm);

    if (f) { /* STATEMENT is written: */
        d->form = f;
        const size_t n = strlen(d->stm);
        memcpy(d->key, d->stm, n);
        memcpy(d->key + n, " is written:", sizeof " is written:");
        d->todo = d->key;
    }
}

/* The error's words: what is wrong, what to do, the name for an error with no words. */
static void diag_words(Diag *const d, const uint16_t user)
{
    d->form = nullptr;
    const char *e = nullptr;

    if (d->dg) {
        e = diag_msgs; /* DG_ n: the nth message */
        for (uint8_t i = 1; i < d->dg; i++)
            e = next_msg(e);
    } else { /* by BC's name: name /TEXT, name /end, name */
        const char *const t = emsg_text(user, d->code);
        const size_t n = strlen(t);
        memcpy(d->key, t, n);
        d->keyend = d->key + n;
        d->keyend[0] = ' ';
        d->keyend[1] = '/';
        const uint32_t room = (uint32_t)(sizeof d->key - 1 - (n + 2));
        upper(d->keyend + 2, d->line + d->col, d->len < room ? d->len : room);
        e = entry(d->key);

        if (!e && !d->len) {
            memcpy(d->keyend, " /end", sizeof " /end");
            e = entry(d->key);
        }

        if (!e) {
            *d->keyend = 0;
            e = entry(d->key);
        }

        if (!e) {
            d->bc = d->key;
            d->what = "{bc} (at `{text}`)";
            d->todo = nullptr;

            if (d->code == E_SN)
                diag_syntax(d);

            return;
        }
    }

    d->bc = e;
    d->what = skip(e);
    d->todo = skip(d->what);
}

/* The item at b's length: a string to its closing quote, a word, or one sign; 0 the end. */
static uint32_t item_len(const char *const b)
{
    if (!*b)
        return 0;

    uint32_t n = 1;

    if (*b == '"') {
        while (b[n] && b[n] != '"')
            n++;
        if (b[n])
            n++; /* the closing quote */
    } else if (is_word(*b)) {
        while (is_word(b[n]))
            n++;
    }

    return n;
}

uint32_t diag_at(
    Diag *const d,
    const uint16_t user,
    const char *const text,
    uint32_t col,
    const uint8_t code,
    const uint8_t dg,
    const uint16_t state
)
{
    d->line = text;
    d->code = code;
    d->dg = dg;
    d->state = state;
    const uint32_t end = (uint32_t)strlen(text); /* the column, at most the end */
    if (col > end)
        col = end;
    while (text[col] == ' ')
        col++;

    d->col = col;
    const uint32_t n = item_len(text + col);
    d->len = n;

    if (!n && code != E_SN) /* nothing here, past what it read: that item, but for a syntax error */
        diag_back(d, col);

    diag_statement(d);
    diag_name(d);
    diag_words(d, user);
    return d->col;
}

void diag_other(Diag *const d, const char *const other, uint32_t len)
{
    if (len > sizeof d->other - 1)
        len = sizeof d->other - 1;

    memcpy(d->other, other, len);
    d->other[len] = 0;
}

static void diag_put_n(Diag *const d, const char *const s, const uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        cons_putc(d->cons, (uint8_t)s[i]);
}

static void diag_put_text(Diag *const d) { diag_put_n(d, d->line + d->col, d->len); }

/* A message's {holder}s. */
typedef enum {
    H_TEXT,
    H_NAME,
    H_STATEMENT,
    H_STM,
    H_OTHER,
    H_BC,
    H_EXPECTED,
    H_FOUND,
    NHOLDERS
} Holder;
static const char *const holders[NHOLDERS] = {
    [H_TEXT] = "text}",
    [H_NAME] = "name}",
    [H_STATEMENT] = "statement}",
    [H_STM] = "stm}",
    [H_OTHER] = "other}",
    [H_BC] = "bc}",
    [H_EXPECTED] = "expected}",
    [H_FOUND] = "found}",
};

/* The holder after a '{' at t; NHOLDERS none. */
static Holder holder_at(const char *const t)
{
    for (uint32_t h = 0; h < NHOLDERS; h++)
        if (!strncmp(t, holders[h], strlen(holders[h])))
            return (Holder)h;

    return NHOLDERS;
}

static void diag_put_holder(Diag *const d, const Holder h)
{
    switch (h) {
    case H_TEXT:
        diag_put_text(d);
        break;

    case H_NAME:
        if (d->namelen)
            diag_put_n(d, d->name, d->namelen);
        else
            diag_put_text(d);

        break;

    case H_STATEMENT:
        cons_puts(d->cons, d->stm[0] ? d->stm : "this");
        break;

    case H_STM:
        if (d->stm[0]) {
            cons_puts(d->cons, d->stm);
            cons_putc(d->cons, ' ');
        }

        cons_puts(d->cons, "statement");
        break;

    case H_OTHER:
        cons_puts(d->cons, d->other);
        break;

    case H_BC:
        cons_puts(d->cons, d->bc);
        break;

    case H_EXPECTED:
        comp_expected(d->cons, d->state);
        break;

    default:
        if (!d->len) {
            cons_puts(d->cons, "the end of the statement");
        } else {
            cons_putc(d->cons, '`');
            diag_put_text(d);
            cons_putc(d->cons, '`');
        }
    }
}

/* Message t, its holders filled; dx.cap: its first letter a capital. */
static void diag_fill(Diag *const d, const char *t)
{
    for (char c; (c = *t++);) {
        const Holder h = c == '{' ? holder_at(t) : NHOLDERS;

        if (c == '{') {
            d->cap = false;
            d->last = 'x';
        }

        if (h == NHOLDERS) {
            if (d->cap) {
                d->cap = false;
                c = (char)upcase((uint8_t)c);
            }

            d->last = c;
            cons_putc(d->cons, (uint8_t)c);
            continue;
        }

        t += strlen(holders[h]);
        diag_put_holder(d, h);
    }
}

/* fill as a sentence: a capital first, a period last unless it ends in one or a ':'. */
static void diag_sentence(Diag *const d, const char *const t)
{
    d->cap = true;
    diag_fill(d, t);
    d->cap = false;

    if (d->last != '.' && d->last != ':')
        cons_putc(d->cons, '.');
}

void diag_what(Diag *const d) { diag_sentence(d, d->what); }

bool diag_todo(Diag *const d)
{
    if (!d->todo || !*d->todo)
        return false;

    diag_sentence(d, d->todo);
    return true;
}

bool diag_shape(Diag *const d)
{
    if (!d->form)
        return false;

    cons_puts(d->cons, d->form);
    return true;
}

void diag_say(Diag *const d)
{
    diag_what(d);
    cons_nl(d->cons);

    if (diag_todo(d))
        cons_nl(d->cons);
    if (d->form) {
        cons_spaces(d->cons, 2);
        diag_shape(d);
        cons_nl(d->cons);
    }
}

void diag_init(Diag *const d, Cons *const co) { d->cons = co; }
