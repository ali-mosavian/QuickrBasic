#!/usr/bin/env python3
"""gen_messages.py [check]: the compile errors' words as src/core/io/msg.h.

  gen_messages.py        write msg.h
  gen_messages.py check  msg.h as the generator writes it

llrm_messages.txt gives each error BC's name, what is wrong and what to do; llrm_syntax_forms.txt
how each statement is written (copies of llrm's QB frontend's). messages.txt adds the ones llrm
lacks, read first, so its entry of a name wins. msg.h holds them as data where DIAG_DATA is set,
and a DG_ number per entry for the compiler's sites that know which one they raise.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COUT = ROOT / "src/core/io/msg.h"
OWN = ROOT / "src/core/io/messages.txt"
LLRM_MESSAGES = ROOT / "src/core/io/llrm_messages.txt"
LLRM_FORMS = ROOT / "src/core/io/llrm_syntax_forms.txt"


def rows(path: Path, parts: int) -> list[list[str]]:
    out = []
    for line in path.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        cells = line.split("|", parts - 1)
        out.append(cells + [""] * (parts - len(cells)))
    return out


def slug(key: str) -> str:
    return "DG_" + re.sub(r"[^A-Z0-9]+", "_", key.upper()).strip("_")


def db(text: str) -> str:
    """One string, 0-ended, as db lines; a quote character as a number."""
    items, run = [], ""
    for c in text:
        if c in "\"'":
            if run:
                items.append(f'"{run}"')
                run = ""
            items.append(str(ord(c)))
        else:
            run += c
    if run:
        items.append(f'"{run}"')
    items.append("0")
    lines, cur = [], []
    for item in items:
        if cur and len(", ".join(cur + [item])) > 90:
            lines.append("        db      " + ",".join(cur))
            cur = []
        cur.append(item)
    lines.append("        db      " + ",".join(cur))
    return "\n".join(lines)


def sources() -> tuple[list[list[str]], list[list[str]]]:
    return rows(OWN, 3) + rows(LLRM_MESSAGES, 3), rows(LLRM_FORMS, 2)


def numbers(msgs: list[list[str]]) -> list[tuple[str, int]]:
    """Each DG_ name and its entry's number, the first entry of a name."""
    out, seen = [], set()
    for i, (key, _, _) in enumerate(msgs, 1):
        name = slug(key)
        if name not in seen:
            seen.add(name)
            out.append((name, i))
    return out


def cstr(text: str) -> str:
    """One string, 0-ended, as a C literal; the array's own 0 ends the list."""
    body = "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else
                   ("\\" + c if c in '"\\' else f"\\x{ord(c):02x}\"\"") for c in text)
    return f'    "{body}\\0"'


def emit_c() -> str:
    msgs, forms = sources()
    out = ["/* generated by tools/gen_messages.py from io/messages.txt, llrm_messages.txt and",
           "   syntax_forms.txt: do not edit. diag_msgs: per entry BC's name [/variant], what is wrong,",
           "   what to do, each 0-ended; an empty name ends it. diag_forms: a statement's first word, its",
           "   form; an empty word ends it. */",
           "#ifndef CORE_IO_MSG_H", "#define CORE_IO_MSG_H", "#include <stdint.h>", "",
           "enum : uint8_t {"]
    out += [f"    {name} = {i}," for name, i in numbers(msgs)]
    out += ["};", "", "#ifdef DIAG_DATA", "static const char diag_msgs[] ="]
    for key, what, todo in msgs:
        out += [cstr(key), cstr(what), cstr(todo)]
    out += ["    \"\";", "static const char diag_forms[] ="]
    for word, form in forms:
        out += [cstr(word), cstr(form)]
    out += ["    \"\";", "#endif", "#endif", ""]
    return "\n".join(out)



if __name__ == "__main__":
    outs = [(COUT, emit_c())]
    if sys.argv[1:] == ["check"]:
        stale = [p.name for p, text in outs if not p.exists() or p.read_text() != text]
        if stale:
            print(" and ".join(stale), "not what the generator writes: run tools/gen_messages.py")
            sys.exit(1)
        sys.exit(0)
    for p, text in outs:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
