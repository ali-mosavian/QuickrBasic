/* A compile error in words, for the person who wrote the line.
 *
 * # How it works
 * An error is its E_* code, its DG_ code (io/msg.h; 0: found by BC's name and the text at the
 * error) and its column in the line's text. diag_at reads the place; diag_say prints what is
 * wrong, what to do, and the statement's form. The wording comes from llrm's front/explain.rs.
 *
 * diag_raise reports an error found off the code (the block pass), raised as if an ERR op at body
 * offset at of line (a program store offset) raised it, never trapped. other is its {other} text,
 * len bytes (31 at most kept). vm.opip is set to an ErrOp (vm/exec.h) of diag's own.
 *
 * # asm structure (src/io/diag.asm, msg.inc)
 * | asm | here | |
 * |---|---|---|
 * | dx_at | diag_at | MIRROR; place error code, dg and state, returns the column the text is about |
 * | dx_raise | diag_raise | MIRROR |
 * | dx_say, dx_what | diag_say, diag_what | MIRROR |
 * | dx_todo, dx_shape | diag_todo, diag_shape | MIRROR; true when printed |
 * | dx_back, dx_stmt, dx_alpha, dx_upper, dx_name, dx_isw, dx_streq, dx_skip, dx_form, dx_find, dx_res, dx_syn, dx_sent, dx_fill, dx_p* | static | MIRROR |
 * | g_dx* data, g_dxr | static (g_dxr an ErrOp) | MIRROR |
 * | DG_* (msg.inc) | DG_* (io/msg.h) | D1 |
 * | g_dxmsg, g_dxfrm | diag_msgs, diag_forms | D1 |
 *
 * - D1. msg.h is generated by tools/x86msg.py; the tables are defined under DIAG_DATA.
 */
#define DIAG_DATA
